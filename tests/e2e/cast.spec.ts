import {test,expect} from '@playwright/test';
import {readFileSync} from 'node:fs';
import {createRequire} from 'node:module';
import {createElement} from 'react';
import {renderToStaticMarkup} from 'react-dom/server';
const requireSource=createRequire(import.meta.url);
requireSource('../load-source.cjs');
const CastSection=requireSource('../../lib/cast-section.tsx').default;
import {titles} from '../../app/titles';
test('hundreds of voice roles remain compact and can be consulted without stretching the card',async({page})=>{
 const roles=['Homer (voice)','Moe (voice)','Abraham (voice)',...Array.from({length:300},(_,i)=>`Personagem secundário ${i} (voice)`)];
 const title={...titles[0],genres:['Animação'],cast:['Dan','Hank'],castProfiles:[{name:'Dan',role:roles.join(' / '),roles},{name:'Hank',role:roles.join(' / '),roles}]};
 const html=renderToStaticMarkup(createElement(CastSection,{title}));
 const css=readFileSync('app/globals.css','utf8').replace(/^@import[^;]+;/gm,'');
 await page.setContent(`<html lang="pt-BR"><head><meta name="viewport" content="width=device-width, initial-scale=1"><style>${css}body{padding:20px}section{max-width:800px;margin:auto}</style></head><body>${html}</body></html>`);
 const card=page.locator('.cast>li').first();
 await expect(card.getByText('Homer / Moe / Abraham',{exact:true})).toBeVisible();
 await expect(card.getByText('Personagem secundário 299',{exact:true})).toBeHidden();
 expect((await card.boundingBox())!.height).toBeLessThan(350);
 await card.locator('summary').click();
 await expect(card.locator('details')).toHaveAttribute('open','');
 const list=card.getByRole('list',{name:'Outros personagens de Dan'});
 await expect(list).toHaveCSS('max-height','220px');
 await card.getByText('Personagem secundário 299',{exact:true}).scrollIntoViewIfNeeded();
 await expect(card.getByText('Personagem secundário 299',{exact:true})).toBeVisible();
 expect((await list.boundingBox())!.height).toBeLessThanOrEqual(220);
 await card.locator('summary').click();
 await expect(card.getByText('Personagem secundário 299',{exact:true})).toBeHidden();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth)).toBe(false);
});
